#!/usr/bin/env python3
"""Generate the additive Goose migration offline from reviewed, pinned references.
No network access or database connections. Run with --check to detect drift.
"""
import argparse,csv,io,json,pathlib,decimal
ROOT=pathlib.Path(__file__).resolve().parents[2]
HERE=pathlib.Path(__file__).resolve().parent
MIGRATION=ROOT/'database/migrations/006_expanded_food_catalogue.sql'
MARKER='MyFit catalogue 006 | '
def rounded(value,places):
 return float(decimal.Decimal(str(value)).quantize(decimal.Decimal(10)**-places,rounding=decimal.ROUND_HALF_UP))
def load():return json.loads((HERE/'foods.json').read_text()),json.loads((HERE/'references.json').read_text())['references']
def build():
 foods,refs=load();rows=[];names=set()
 for food in foods:
  name=food['name'];key=name.strip().lower()
  assert key not in names and len(name)<=160,name
  names.add(key)
  if 'reference' in food:
   ref=refs[food['reference']];values=list(ref['values']);values[0]=rounded(values[0],1)
   source=ref['source']+' Reference: '+ref['description']+'.'
  else:
   ingredients=food['ingredients'];yield_g=food['yield_g']
   assert yield_g>0 and ingredients
   assert yield_g<=sum(i['grams'] for i in ingredients)+.001,'Yield exceeds ingredients: '+name
   values=[rounded(sum(refs[i['reference']]['values'][n]*i['grams']/100 for i in ingredients)*100/yield_g,0 if n==0 else 1) for n in range(5)]
   parts=[f"{i['grams']:g} g {refs[i['reference']]['description']} [{i['reference']}]" for i in ingredients]
   source=('Approximate MyFit standard recipe model; not a measured restaurant dish. '+
           '; '.join(parts)+f'. Estimated final cooked/ready-to-eat yield {yield_g:g} g. '+food['method']+
           ' Counted oil is retained oil, not the frying bath. Unlisted spices/salt are omitted. No nutrient-retention or fermentation factors applied. '+
           'Grain milled to flour uses the stated whole-grain reference where applicable. '+
           'IFCT carbohydrate is available carbohydrate plus fibre; USDA uses total carbohydrate. '+
           'Ingredient references: '+'; '.join(dict.fromkeys(refs[i['reference']]['source'] for i in ingredients))+'.')
  assert all(isinstance(x,(int,float)) and 0<=x<=(1000 if n==0 else 100) for n,x in enumerate(values)),name
  servings=[['Grams',1],['100 grams',100]]+food['servings']
  assert len({s[0].lower() for s in servings})==len(servings),name
  assert all(0<grams<=10000 for _,grams in servings),name
  assert '100 g' not in name # basis comes from the schema, not ambiguous name suffixes
  rows.append({'name':name,'brand':food.get('brand',''),'calories':values[0],'protein':values[1],'carbs':values[2],'fat':values[3],'fibre':values[4],'source':MARKER+'Per 100 g edible portion; serving weights estimated. '+source,'servings':[{'name':n,'grams':g} for n,g in servings]})
 return rows

def render(rows):
 payload='[\n'+',\n'.join(json.dumps(r,ensure_ascii=False,separators=(',',':')) for r in rows)+'\n]'
 return '''-- Generated by database/catalogue/generate.py; edit reviewed JSON inputs, then regenerate.
-- All five nutrients per 100 g edible portion (kcal; grams), including beverages.
-- +goose Up
-- Serialize catalogue writers during this short transaction, without blocking SELECT.
-- Prevent a concurrent seed/application insert from racing the name existence check.
LOCK TABLE foods IN SHARE ROW EXCLUSIVE MODE;
WITH catalogue AS (
 SELECT * FROM jsonb_to_recordset($myfit_foods$
'''+payload+'''
$myfit_foods$::jsonb) AS c(name text,brand text,calories double precision,protein double precision,
 carbs double precision,fat double precision,fibre double precision,source text,servings jsonb)
), inserted AS (
 INSERT INTO foods(owner_id,name,brand,calories,protein,carbs,fat,fibre,source,approximate)
 SELECT NULL,c.name,c.brand,c.calories,c.protein,c.carbs,c.fat,c.fibre,c.source,true
 FROM catalogue c
 WHERE NOT EXISTS (SELECT 1 FROM foods f WHERE f.owner_id IS NULL AND lower(btrim(f.name))=lower(btrim(c.name)))
 RETURNING id,name
)
INSERT INTO servings(food_id,name,grams)
 SELECT i.id,s.name,s.grams FROM inserted i JOIN catalogue c ON c.name=i.name
 CROSS JOIN LATERAL jsonb_to_recordset(c.servings) AS s(name text,grams double precision);
-- Existing foods/servings, private foods, favourites and historical snapshots are never updated.
-- A repeated Up inserts neither duplicate foods nor duplicate servings.

-- +goose Down
-- Intentionally retain additive reference data: users may have favourited/logged it.
-- Do not delete catalogue rows or rewrite snapshots during application rollback.
SELECT 1;
'''
def review_csv(rows):
 foods,_=load();categories={f['name']:f['category'] for f in foods}
 out=io.StringIO();writer=csv.writer(out,lineterminator='\n')
 writer.writerow(['food','category','basis','kcal','protein_g','carbohydrate_g','fat_g','fibre_g','estimated_servings'])
 for r in rows:
  writer.writerow([r['name'],categories[r['name']],'100 g edible portion',r['calories'],r['protein'],r['carbs'],r['fat'],r['fibre'],'; '.join(f"{s['name']}: {s['grams']:g} g" for s in r['servings'])])
 return out.getvalue()
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 rows=build();text=render(rows);csv_text=review_csv(rows);csv_path=HERE/'review.csv'
 if args.check:
  if not MIGRATION.exists() or MIGRATION.read_text()!=text or not csv_path.exists() or csv_path.read_text()!=csv_text:raise SystemExit('Generated catalogue migration is stale')
 else:
  MIGRATION.write_text(text);csv_path.write_text(csv_text)
 print(f'{len(rows)} new shared foods; generated migration '+('verified' if args.check else 'written'))
if __name__=='__main__':main()
